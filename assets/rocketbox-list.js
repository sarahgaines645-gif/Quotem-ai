/* THE ROCKETBOX CATALOGUE — 113 avatars, listed, not downloaded.
 *
 * Microsoft released these under the MIT licence, and raw.githubusercontent.com
 * serves them with `Access-Control-Allow-Origin: *`. So the browser can fetch a
 * character and its textures STRAIGHT FROM MICROSOFT at the moment Sarah picks
 * one — no 113 avatars sitting in our repo, no 4GB of TGA, nothing to keep in
 * sync. Only the one she settles on gets committed.
 *
 * Every avatar has the same shape on disk:
 *   {group}/{name}/{name}.png                    the preview picture
 *   {group}/{name}/Export/{name}_facial.fbx      the model WITH 175 blendshapes
 *   {group}/{name}/Textures/                     its .tga maps
 *
 * ⚠️ The textures sit in a SIBLING folder to the .fbx, so the loader has to be
 * told where they are (`setResourcePath`) — otherwise she loads perfectly and
 * renders as a grey mannequin.
 */
